package sandbox

import (
	"encoding/hex"
	"encoding/json"
	"fmt"
	"math"
	"path/filepath"
	"reflect"
	"sort"
	"strconv"
	"strings"

	"github.com/moby/moby/api/types/container"
	"github.com/moby/moby/api/types/mount"
	"github.com/moby/moby/client"
	ocispec "github.com/opencontainers/image-spec/specs-go/v1"
	"github.com/ryanflachman-liatrio/jig/internal/step"
	"github.com/ryanflachman-liatrio/jig/internal/workflow"
)

// containerCreateSpec is worker-owned input to a pure configuration builder.
// The runtime must verify the private staging owner and mapped UID/GID, persist
// the image lock and acknowledge intent before sending the resulting request.
// This builder grants no policy, filesystem, or lifecycle authority.
type containerCreateSpec struct {
	step        *workflow.Step
	effective   Effective
	image       client.ImageInspectResult
	binding     BindingData
	phase       step.ContainerPhase
	stagingRoot string
	uid, gid    int
	inputEnv    map[string]string
}

func buildContainerCreate(s containerCreateSpec) (client.ContainerCreateOptions, error) {
	fail := func() (client.ContainerCreateOptions, error) {
		return client.ContainerCreateOptions{}, fmt.Errorf("unsupported contained command configuration")
	}
	if s.step == nil || s.step.Type != workflow.StepCommand || s.step.Isolation != workflow.IsolationNone || len(s.step.Secrets) != 0 || len(s.step.WorkspaceRequirements) != 0 {
		return fail()
	}
	request := s.step.ResolvedSandbox()
	if err := workflow.ValidateSandboxRequest(request); err != nil {
		return fail()
	}
	profile := request.Profile
	if profile == nil || profile.Runtime != "docker" || profile.Pull != "never" || profile.Network != "none" {
		return fail()
	}
	// Effective resources are supplied by frozen operator authorization. Do not
	// substitute fixture defaults or silently raise insufficient limits.
	if !reflect.DeepEqual(s.effective.Request, request) || s.effective.NanoCPUs <= 0 || s.effective.MemoryBytes < 6<<20 || s.effective.PIDs <= 0 || s.effective.PIDs > math.MaxInt32 {
		return fail()
	}
	if s.uid <= 0 || s.gid <= 0 || int64(s.uid) > math.MaxInt32 || int64(s.gid) > math.MaxInt32 || !filepath.IsAbs(s.stagingRoot) || filepath.Clean(s.stagingRoot) != s.stagingRoot || s.stagingRoot == string(filepath.Separator) {
		return fail()
	}
	native := s.binding.NativePlatform
	if native != "linux/amd64" && native != "linux/arm64" {
		return fail()
	}
	if profile.Platform != "" && string(profile.Platform) != native && !(profile.Platform == "linux/arm64/v8" && native == "linux/arm64") {
		return fail()
	}
	if nativePlatform(s.image.Os, s.image.Architecture, s.image.Variant) != native || s.image.Config == nil || len(s.image.Config.Volumes) != 0 {
		return fail()
	}
	digest, err := hex.DecodeString(strings.TrimPrefix(s.image.ID, "sha256:"))
	if err != nil || len(digest) != 32 || !strings.HasPrefix(s.image.ID, "sha256:") || s.image.ID != strings.ToLower(s.image.ID) {
		return fail()
	}
	p := s.phase
	if p.Phase != "main" && p.Phase != "validation" || p.State != step.ContainerIntent || p.ContainerID != "" || p.ImageID != s.image.ID || p.DaemonID != s.binding.DaemonID || p.StepID != s.step.ID || p.EndpointID == "" {
		return fail()
	}
	validationPhase := p.Phase == "validation"
	// Reuse ownership identity validation without pretending a pure builder has
	// engine history; main/validator ordering is enforced by the scheduler.
	identity := p
	identity.Phase = "main"
	if err := (step.ContainerLedger{}).Check(identity); err != nil {
		return fail()
	}
	if p.Name != "jig-"+p.Nonce+"-"+p.Phase {
		return fail()
	}
	command := []string{"/bin/sh", "-c", s.step.Run}
	if validationPhase {
		if s.step.Validate == nil || s.step.Validate.Command == "" {
			return fail()
		}
		command = []string{"/bin/sh", "-c", s.step.Validate.Command}
	} else if s.step.Script != "" {
		if s.step.Run != "" {
			return fail()
		}
		command = []string{"/bin/sh", "/captures/command.sh"}
	} else if s.step.Run == "" {
		return fail()
	}
	if len(strings.Join(command, "")) > 1<<20 || strings.ContainsRune(strings.Join(command, ""), 0) {
		return fail()
	}
	env := map[string]string{"PATH": "/usr/local/go/bin:/usr/local/bin:/usr/bin:/bin", "HOME": "/home/jig", "USER": "jig", "LOGNAME": "jig", "SHELL": "/bin/sh", "TMPDIR": "/tmp", "LANG": "C.UTF-8", "GOPATH": "/go", "GOMODCACHE": "/go/pkg/mod", "GOTOOLCHAIN": "local", "GOPROXY": "off", "GOSUMDB": "off"}
	for key, value := range profile.Env {
		env[key] = value
	}
	// Input bindings are generated by staging, never arbitrary host paths.
	if len(s.inputEnv) != len(s.step.Inputs) || len(s.inputEnv) > step.ContainerInputCount {
		return fail()
	}
	for i, in := range s.step.Inputs {
		key := "JIG_INPUT_" + workflow.InputEnvironmentName(in.As)
		value := fmt.Sprintf("/inputs/%03d", i+1)
		if strings.TrimSpace(in.As) == "" || s.inputEnv[key] != value {
			return fail()
		}
		if _, exists := env[key]; exists {
			return fail()
		}
		env[key] = value
	}
	keys := make([]string, 0, len(env))
	for key := range env {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	// Docker merges image Env with Config.Env. An absolute env -i entrypoint
	// explicitly clears inherited image values for the workload shell.
	args := []string{"-i"}
	for _, key := range keys {
		args = append(args, key+"="+env[key])
	}
	args = append(args, command...)
	stop := 2
	init := true
	pids := s.effective.PIDs
	labels := map[string]string{"jig.run": p.RunID, "jig.step": p.StepID, "jig.execution": p.Nonce, "jig.phase": p.Phase, "jig.generation": strconv.Itoa(p.Generation), "jig.iteration": strconv.Itoa(p.Iteration), "jig.attempt": strconv.Itoa(p.Attempt), "jig.daemon": p.DaemonID, "jig.endpoint": p.EndpointID, "jig.image": p.ImageID}
	mounts := []mount.Mount{}
	for _, m := range []struct {
		name, target string
		readOnly     bool
	}{{"workspace", "/workspace", false}, {"scratch", "/scratch", false}, {"inputs", "/inputs", true}, {"captures", "/captures", true}} {
		mounts = append(mounts, mount.Mount{Type: mount.TypeBind, Source: filepath.Join(s.stagingRoot, m.name), Target: m.target, ReadOnly: m.readOnly, BindOptions: &mount.BindOptions{Propagation: mount.PropagationRPrivate, NonRecursive: true}})
	}
	tmpfs := fmt.Sprintf("rw,nosuid,nodev,noexec,size=67108864,mode=0700,uid=%d,gid=%d", s.uid, s.gid)
	options := client.ContainerCreateOptions{Name: p.Name, Platform: &ocispec.Platform{OS: "linux", Architecture: strings.TrimPrefix(native, "linux/")}, Config: &container.Config{
		Image: s.image.ID, User: fmt.Sprintf("%d:%d", s.uid, s.gid), Entrypoint: []string{"/usr/bin/env"}, Cmd: args, WorkingDir: "/workspace", Env: []string{}, AttachStdout: true, AttachStderr: true, NetworkDisabled: true, Healthcheck: &container.HealthConfig{Test: []string{"NONE"}}, StopSignal: "SIGTERM", StopTimeout: &stop, Labels: labels,
	}, HostConfig: &container.HostConfig{
		ReadonlyRootfs: true, NetworkMode: "none", CapDrop: []string{"ALL"}, SecurityOpt: []string{"no-new-privileges:true"}, IpcMode: "private", CgroupnsMode: "private", Init: &init, RestartPolicy: container.RestartPolicy{Name: "no"}, LogConfig: container.LogConfig{Type: "none"}, Mounts: mounts, Tmpfs: map[string]string{"/tmp": tmpfs, "/home/jig": tmpfs}, ShmSize: 16 << 20,
		Resources: container.Resources{NanoCPUs: s.effective.NanoCPUs, Memory: s.effective.MemoryBytes, MemorySwap: s.effective.MemoryBytes, PidsLimit: &pids},
	}}
	raw, err := json.Marshal(container.CreateRequest{Config: options.Config, HostConfig: options.HostConfig})
	if err != nil || len(raw) > executionRequestBytes {
		return fail()
	}
	return options, nil
}
